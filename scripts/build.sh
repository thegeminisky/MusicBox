#!/usr/bin/env bash
# Linux build for GitHub Actions. Mirrors scripts/build.ps1 step by step.
# Required env: ANDROID_HOME, JAVA_HOME
# Optional env: MB_VERSION_NAME, MB_VERSION_CODE, KS_PATH, KS_PASS, KS_ALIAS, KEY_PASS
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$ROOT/app/src/main"
OUT="$ROOT/build"
DIST="$ROOT/dist"

BT="${ANDROID_HOME}/build-tools/34.0.0"
ANDROID_JAR="${ANDROID_HOME}/platforms/android-34/android.jar"
AAPT2="$BT/aapt2"
D8="$BT/lib/d8.jar"
APKSIGNER="$BT/lib/apksigner.jar"
ZIPALIGN="$BT/zipalign"
JAVA="${JAVA_HOME}/bin/java"
JAVAC="${JAVA_HOME}/bin/javac"
JAR="${JAVA_HOME}/bin/jar"
PY=python3

for f in "$AAPT2" "$D8" "$APKSIGNER" "$ZIPALIGN" "$ANDROID_JAR" "$JAVAC"; do
  if [ ! -f "$f" ]; then echo "missing build input: $f" >&2; exit 1; fi
done

# ---- version -------------------------------------------------------------
# CI passes the tag version (v1.1.3 -> 1.1.3). Locally it falls back to the
# same MAJOR.MINOR.PATCH rule as build.ps1.
read_cfg() {
  grep -E "^$1=" "$ROOT/version.config" | head -1 | cut -d= -f2 | tr -d ' \r'
}
BASE_COMMIT="$(read_cfg BASE_COMMIT)"
MAJOR="$(read_cfg MAJOR)"
MINOR="$(read_cfg MINOR)"
if [ "$BASE_COMMIT" = "ROOT" ]; then
  TOTAL="$(git rev-list --count HEAD 2>/dev/null || echo 1)"
  PATCH=$((TOTAL - 1))
else
  PATCH="$(git rev-list --count "${BASE_COMMIT}..HEAD" 2>/dev/null || echo 0)"
fi
[ "$PATCH" -lt 0 ] && PATCH=0
DEFAULT_VERSION="$MAJOR.$MINOR.$PATCH"
DEFAULT_CODE=$((MAJOR * 10000 + MINOR * 100 + PATCH))

VERSION_NAME="${MB_VERSION_NAME:-$DEFAULT_VERSION}"
VERSION_CODE="${MB_VERSION_CODE:-$DEFAULT_CODE}"
# X.Y.Z -> X*10000+Y*100+Z when only a name was supplied
if [ -n "${MB_VERSION_NAME:-}" ] && [ -z "${MB_VERSION_CODE:-}" ]; then
  IFS='.' read -r a b c <<< "$VERSION_NAME"
  VERSION_CODE=$((a * 10000 + b * 100 + c))
fi
echo "version $VERSION_NAME (code $VERSION_CODE)"

rm -rf "$OUT"
mkdir -p "$OUT/gen" "$OUT/classes" "$OUT/dex" "$DIST"

# ---- 1 aapt2 compile -----------------------------------------------------
echo "[1/10] aapt2 compile"
"$AAPT2" compile --dir "$SRC/res" -o "$OUT/res.zip"

# ---- 2 aapt2 link --------------------------------------------------------
echo "[2/10] aapt2 link"
"$AAPT2" link -o "$OUT/base.apk" -I "$ANDROID_JAR" \
  --manifest "$SRC/AndroidManifest.xml" --java "$OUT/gen" \
  --min-sdk-version 26 --target-sdk-version 34 \
  --version-code "$VERSION_CODE" --version-name "$VERSION_NAME" "$OUT/res.zip"

# ---- 3 BuildInfo ---------------------------------------------------------
echo "[3/10] generate BuildInfo"
FULL_HASH="$(git rev-parse HEAD 2>/dev/null || echo unknown)"
BUILD_TIME="$(date '+%Y-%m-%d %H:%M:%S')"
GENPKG="$OUT/gen/com/mbox/music"
mkdir -p "$GENPKG"
cat > "$GENPKG/BuildInfo.java" <<EOF
package com.mbox.music;

/** Generated by CI - do not edit. */
public final class BuildInfo {
    public static final String VERSION_NAME = "$VERSION_NAME";
    public static final String FULL_VERSION = "$VERSION_NAME";
    public static final String BUILD_TIME = "$BUILD_TIME";
    public static final String COMMIT_HASH = "$FULL_HASH";
}
EOF

# ---- 4 collect sources ---------------------------------------------------
echo "[4/10] collect sources"
find "$SRC/java" "$OUT/gen" -name '*.java' > "$OUT/sources.txt"

# ---- 5 javac -------------------------------------------------------------
echo "[5/10] javac"
"$JAVAC" -encoding UTF-8 -source 8 -target 8 -Xlint:-options -nowarn \
  -classpath "$ANDROID_JAR" -d "$OUT/classes" "@$OUT/sources.txt"

# ---- 6 jar ---------------------------------------------------------------
echo "[6/10] jar"
(cd "$OUT/classes" && "$JAR" cf "$OUT/classes.jar" .)

# ---- 7 d8 ----------------------------------------------------------------
echo "[7/10] d8"
"$JAVA" -cp "$D8" com.android.tools.r8.D8 --release --min-api 26 \
  --lib "$ANDROID_JAR" --output "$OUT/dex" "$OUT/classes.jar"

# ---- 8 assemble ----------------------------------------------------------
echo "[8/10] assemble apk"
"$PY" "$ROOT/scripts/assemble.py" "$OUT/base.apk" "$OUT/dex/classes.dex" "$OUT/unsigned.apk"

# ---- 9 zipalign ----------------------------------------------------------
echo "[9/10] zipalign"
"$ZIPALIGN" -p -f 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

# ---- 10 apksigner --------------------------------------------------------
echo "[10/10] apksigner"
APK="$DIST/musicbox.apk"
KS_PATH="${KS_PATH:-$ROOT/key_exchange/release.keystore}"
KS_PASS="${KS_PASS:-}"
KS_ALIAS="${KS_ALIAS:-musicbox}"
KEY_PASS="${KEY_PASS:-$KS_PASS}"
if [ ! -f "$KS_PATH" ]; then
  echo "keystore missing: $KS_PATH" >&2
  exit 1
fi
"$JAVA" -jar "$APKSIGNER" sign \
  --ks "$KS_PATH" --ks-key-alias "$KS_ALIAS" \
  --ks-pass "pass:$KS_PASS" --key-pass "pass:$KEY_PASS" \
  --v1-signing-enabled true --v2-signing-enabled true --min-sdk-version 26 \
  --out "$APK" "$OUT/aligned.apk"
"$JAVA" -jar "$APKSIGNER" verify --print-certs "$APK" | head -3
ls -l "$APK"
